"""Blind independent E11.08: two-node equations and determinant, original Fig11.11."""
import sympy as sp
s=sp.symbols('s')
Rs,Rd,Ci,Cl,gm,vin=sp.symbols('RS RD Cin CL gm vin',positive=True)
vg,vo=sp.symbols('vg vout')
print('CONNECTIVITY: Vin through RS to gate node vg; Cin gate-ground; M1 source-ground; drain=vout; RD drain-VDD; CL drain-ground.')
print('MODEL: lambda=0 so ro=infinity, VDD AC-ground, ideal MOS gate conduction0. No gate-drain capacitance shown; only given Cin and CL. Grounded source means no signal body-source voltage in intended model.')
kg=sp.Eq((vg-vin)/Rs+s*Ci*vg,0)
kd=sp.Eq(vo/Rd+s*Cl*vo+gm*vg,0)
print('Gate KCL:',kg)
print('Drain KCL:',kd)
sol=sp.solve([kg,kd],[vg,vo])
H=sp.factor(sol[vo]/vin)
print('vg/vin:',sp.factor(sol[vg]/vin))
print('Derived internal H(s):',H)
Y=sp.Matrix([[1/Rs+s*Ci,0],[gm,1/Rd+s*Cl]])
det=sp.factor(Y.det())
print('Input-zero natural-system matrix:',Y)
print('Characteristic determinant:',det)
roots=sp.solve(det,s)
print('Natural poles:',roots)
assert sp.simplify(det-(1+s*Rs*Ci)*(1+s*Rd*Cl)/(Rs*Rd))==0
assert set(roots)=={-1/(Rs*Ci),-1/(Rd*Cl)}
assert sp.simplify(H+gm*Rd/((1+s*Rs*Ci)*(1+s*Rd*Cl)))==0
print('No numerator cancellation for positive finite nonzero values. Two poles negative real; if timeconstants coincide, one repeated pole multiplicity2.')
print('Pole locations s_p,in=-1/(RS Cin), s_p,out=-1/(RD CL).')
print('Positive angular corners win=1/(RS Cin), wout=1/(RD CL); f=omega/(2pi).')
print('RC cross-check: zero independent Vin by short; Cin sees RS toground because ideal gate does not draw conduction. No drain-to-gate feedback -> upper-right matrix0. Output sees RD when vin0->vg0 and lambda0.')
print('gm affects transfer numerator and driven output, not this lower-triangular determinant.')
print('Cin->0 transfer:',sp.limit(H,Ci,0))
print('CL->0 transfer:',sp.limit(H,Cl,0))
print('No pole ordering follows from unspecified component values; cannot assert input pole islower.')
print('BLIND TWO-NODE POLE PASS')
