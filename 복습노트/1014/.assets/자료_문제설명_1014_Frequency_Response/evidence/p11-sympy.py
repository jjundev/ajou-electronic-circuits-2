"""Blind independent E11.09 CG poles from actual two-node current equations."""
import sympy as sp
s=sp.symbols('s')
Rs,Rd,Ci,Cl,g,vin=sp.symbols('RS RD Cin CL gm vin',positive=True)
vx,vo=sp.symbols('vx vout')
print('ACTUAL: gate fixedVb -> ACground; sourcevx is afterRS fromVin, withCinx-ground; drainvout hasRD toVDD andCL-ground. Input enters source, notgate.')
print('MODEL lambda0 -> roinfinity; bodyeffect ignored; gatecurrent0. SuppliesACground.')
print('vgs=-vx, controlled drain-to-source current=-gm vx; hence source-to-drain current=+gm vx. Positive current entering source transistor=gm vx -> source driving resistance1/gm independent ofdrainvoltage.')
ks=sp.Eq((vx-vin)/Rs+s*Ci*vx+g*vx,0)
kd=sp.Eq(vo/Rd+s*Cl*vo-g*vx,0)
print('Source KCL:',ks);print('Drain KCL:',kd)
sol=sp.solve([ks,kd],[vx,vo]);H=sp.factor(sol[vo]/vin)
Y=sp.Matrix([[1/Rs+g+s*Ci,0],[-g,1/Rd+s*Cl]])
det=sp.factor(Y.det());roots=sp.solve(det,s)
print('Natural-response matrix:',Y)
print('Characteristic determinant:',det)
print('Pole roots:',roots)
print('Internal H:',H)
assert sp.simplify(H-g*Rd/((1+g*Rs+s*Rs*Ci)*(1+s*Rd*Cl)))==0
assert all(any(sp.simplify(root-target)==0 for root in roots) for target in [-(g+1/Rs)/Ci,-1/(Rd*Cl)])
Req=1/(1/Rs+g)
print('Source input-zero equivalent resistance RS||1/gm:',sp.factor(Req))
print('Positive source corner:',sp.factor(1/(Req*Ci)))
print('Positive drain corner:',1/(Rd*Cl))
print('Setting independentVin0 groundsRS left endpoint only; sourcevx remains a natural/testnode, notidentically0. Source inputresistance provides additional shunt1/gm.')
print('No drain-to-source voltagefeedback because roinfinity -> upperrightmatrix0. Thus sourcepole independentofRD,CL.')
print('RS->0 sourcecorner ->infinity:',sp.limit((g+1/Rs)/Ci,Rs,0,dir='+'))
print('RS->infinity sourcecorner ->gm/Cin:',sp.limit((g+1/Rs)/Ci,Rs,sp.oo))
print('gm->0 sourcecorner ->1/(RSCin):',sp.limit((g+1/Rs)/Ci,g,0))
print('Corner Hz frequencies=positive angularcorners/(2pi). No fixedpoleordering withoutvalues.')
print('If bodyeffect included, gm is replaced bygm+gmb in sourcecurrent; selectedclassroommodel intentionallyomitsgmb.')
print('BLIND TWO-NODE CG POLE PASS')
