"""Blind independent P11.12 three-node equations, two energy-storage nodes."""
import sympy as sp
s=sp.symbols('s')
Rs,Rp,Rd,Ci,Cl,g,vin=sp.symbols('RS RP RD Cin CL gm vin',positive=True)
x,z,y=sp.symbols('vX vS vout')
print('ACTUAL Fig11.67: Vin-RS-X; Cin X-ground; RP betweenX andtransistorsourceS. GatefixedVb ACground; drainoutput hasRD toVDD ACground andCL-ground. X is not thetransistorsource.')
print('MODEL lambda0, idealgate0current, bodyeffectignored; no capacitance atS and no othercaps. No drainvoltagefeedback toS.')
print('vgs=-vS, drain-to-source controlledcurrent=-gm vS, source-to-drain=+gm vS.')
kx=sp.Eq((x-vin)/Rs+s*Ci*x+(x-z)/Rp,0)
ks=sp.Eq((z-x)/Rp+g*z,0)
kout=sp.Eq(y/Rd+s*Cl*y-g*z,0)
sol=sp.solve([kx,ks,kout],[x,z,y])
print('X KCL:',kx);print('S KCL:',ks);print('Output KCL:',kout)
zx=sp.simplify(sp.solve(ks,z)[0]/x)
print('vS/vX:',zx)
Ix=sp.simplify((x-sp.solve(ks,z)[0])/Rp)
Rbranch=sp.factor(x/Ix)
print('CurrentfromX throughRP thenintotransistor:',Ix)
print('Series sourcepath resistance:',Rbranch)
assert sp.simplify(Rbranch-(Rp+1/g))==0
Y=sp.Matrix([[1/Rs+s*Ci+1/Rp,-1/Rp,0],[-1/Rp,1/Rp+g,0],[0,-g,1/Rd+s*Cl]])
det=sp.factor(Y.det());roots=sp.solve(det,s)
win=sp.factor((1/Rs+1/(Rp+1/g))/Ci)
wout=1/(Rd*Cl)
print('Three-node characteristic determinant:',det)
print('Degree in s:',sp.degree(sp.together(det).as_numer_denom()[0],s))
print('Poles:',roots)
assert sp.degree(sp.together(det).as_numer_denom()[0],s)==2
assert all(any(sp.simplify(root-target)==0 for root in roots) for target in [-win,-wout])
print('Input equivalent resistance:',sp.factor(1/(1/Rs+1/(Rp+1/g))))
print('Positive inputcorner:',win)
print('Positive outputcorner:',wout)
print('Internal H:',sp.factor(sol[y]/vin))
print('Inputzero groundsRSleftendpoint only, notX orS; Cinsees RS parallel(RP+1/gm). RP has no storage and adds no pole.')
print('RP->0 inputcorner:',sp.limit(win,Rp,0))
assert sp.simplify(sp.limit(win,Rp,0)-(1/Rs+g)/Ci)==0
print('RP->infinity inputcorner:',sp.limit(win,Rp,sp.oo))
assert sp.simplify(sp.limit(win,Rp,sp.oo)-1/(Rs*Ci))==0
print('Derivative ofinputcorner vsRP:',sp.factor(sp.diff(win,Rp)))
print('RP arbitraryparasitic ininputseries path, not an assumedlarge AC-grounddegenerationresistor. Keep1/gm; do not assumegmRP>>1.')
print('All Hzcornerfrequencies are angularcorners/(2pi); signedspoles negative. No numericvalues invented.')
print('BLIND THREE-NODE/TWO-POLE SYMBOLIC PASS')
