"""Blind independent E11.04 derivation from original circuit only; lambda=0."""
import sympy as sp
s=sp.symbols('s')
gm,RD,CL,vin,w=sp.symbols('gm RD CL vin omega', positive=True)
vo=sp.symbols('vout')
print('CONNECTIVITY: gate=vin relative to ground; source=ground; drain=vout; RD drain-to-VDD; CL drain-to-ground.')
print('MODEL: biased saturation small signal, lambda=0 so ro=infinity; VDD is AC ground; vgs=vin.')
print('Positive gm*vin current leaves drain to grounded source. Positive output voltage is drain relative to ground.')
kcl=sp.Eq(vo/RD+s*CL*vo+gm*vin,0)
sol=sp.solve(kcl,vo)[0]
H=sp.simplify(sol/vin)
print('Drain KCL:',kcl)
print('H(s) derived by solve:',H)
assert sp.simplify(H+gm*RD/(1+s*RD*CL))==0
print('Output short circuit current into transistor = gm*vin; Gm = gm.')
print('Input-zero output impedance = RD || 1/(s*CL); H = -Gm*Zout.')
poles=sp.solve(sp.denom(H),s)
print('Pole:',poles)
print('Low-frequency gain:',sp.simplify(H.subs(s,0)))
Hjw=sp.simplify(H.subs(s,sp.I*w))
Re=sp.simplify(sp.re(Hjw)); Im=sp.simplify(sp.im(Hjw))
mag2=sp.simplify(Hjw*sp.conjugate(Hjw))
print('H(jw):',Hjw)
print('real:',Re)
print('imag:',Im)
print('magnitude squared:',mag2)
print('Magnitude = gm*RD/sqrt(1+(omega*RD*CL)**2)')
assert sp.simplify(mag2-(gm*RD)**2/(1+(w*RD*CL)**2))==0
print('Phase: principal theta=pi-atan(omega*RD*CL); positive-frequency H is quadrant II.')
print('Equivalent continuous branch theta=-pi-atan(omega*RD*CL), differing by 2*pi.')
x=sp.symbols('x',positive=True)
normalized=-1/(1+sp.I*x)
theta=sp.pi-sp.atan(x)
unit_complex=sp.simplify(normalized/sp.sqrt(sp.simplify(normalized*sp.conjugate(normalized))))
phase_complex=sp.simplify(sp.cos(theta)+sp.I*sp.sin(theta))
print('Principal phase unit-complex residual:',sp.simplify(unit_complex-phase_complex))
assert sp.simplify(unit_complex-phase_complex)==0
print('Unwrapped/principal phase exp residual:',sp.simplify(sp.exp(sp.I*(-sp.pi-sp.atan(x)))-sp.exp(sp.I*theta)))
print('Half-power at omega_p:',sp.simplify((mag2/(gm*RD)**2).subs(w,1/(RD*CL))))
assert sp.simplify((mag2/(gm*RD)**2).subs(w,1/(RD*CL)))==sp.Rational(1,2)
print('omega_p=1/(RD*CL) rad/s; f_p=1/(2*pi*RD*CL) Hz.')
print('At pole: magnitude=gm*RD/sqrt(2), principal phase=3*pi/4; equivalent unwrapped=-5*pi/4.')
print('DC magnitude:',sp.limit(sp.sqrt(mag2),w,0))
print('High-frequency magnitude:',sp.limit(sp.sqrt(mag2),w,sp.oo))
print('CL->0 transfer:',sp.limit(H,CL,0))
print('High-frequency omega*H(jw):',sp.limit(w*Hjw,w,sp.oo))
M=gm*RD/sp.sqrt(1+x*x)
slope=sp.simplify(20*x*sp.diff(sp.log(M),x))
print('dB/decade slope:',slope)
print('High-frequency slope:',sp.limit(slope,x,sp.oo))
print('No physical numeric parameters were invented; normalized exact x=1 half-power check only.')
print('BLIND SYMBOLIC PASS')
